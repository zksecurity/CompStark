#!/usr/bin/env python3
"""Generate the scalar Keccak round and its unboxed recursive permutation loop."""
from pathlib import Path

lanes = [f'a{i}' for i in range(25)]
args = ' '.join(lanes)
params = f'({args} : UInt64)'
rho = [0, 1, 62, 28, 27, 36, 44, 6, 55, 20, 3, 10, 43, 25, 39,
       41, 45, 15, 21, 8, 18, 2, 61, 56, 14]
lines = ['''/-
Copyright (c) 2026 zkSecurity. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
-/
module

public import VCVio.Algorithms.Keccak

/-! # Scalar Keccak-f[1600]

Generated by `scripts/gen_keccak.py`. Lanes are ordered `x + 5*y`. The continuation
keeps all 25 words unboxed between rounds; rotations have immediate offsets.
-/

public section
namespace CompStark.Keccak

/-- One straight-line Keccak round, passing its 25 output lanes to `k`. -/
@[expose, inline] def roundWith {α : Type} (k : ''' + ' → '.join(['UInt64'] * 25 + ['α']) + ')\n    (rc : UInt64)\n    ' + params + ' : α :=']
for x in range(5):
    lines.append(f"  let c{x} := " + ' ^^^ '.join(f'a{x+5*y}' for y in range(5)))
for x in range(5):
    lines.append(f'  let d{x} := c{(x+4)%5} ^^^ ((c{(x+1)%5} <<< 1) ||| (c{(x+1)%5} >>> 63))')
for i in range(25):
    lines.append(f'  let t{i} := a{i} ^^^ d{i%5}')
for y in range(5):
    for x in range(5):
        i = x+5*y
        dest = y+5*((2*x+3*y)%5)
        expr = f'((t{i} <<< {rho[i]}) ||| (t{i} >>> {64-rho[i]}))'
        lines.append(f'  let b{dest} := {expr}')
for y in range(5):
    for x in range(5):
        i = x+5*y
        expr = f'b{i} ^^^ (~~~b{(x+1)%5+5*y} &&& b{(x+2)%5+5*y})'
        if i == 0:
            expr = f'({expr}) ^^^ rc'
        lines.append(f'  let o{i} := {expr}')
lines.append('  k ' + ' '.join(f'o{i}' for i in range(25)))
lines.extend(['', '/-- The scalar loop, with round constants starting at `r`. -/',
              '@[expose] def permute : Nat → Nat → ' + ' → '.join(['UInt64'] * 25 + ['Array UInt64']),
              '  | 0, _, ' + ', '.join(lanes) + ' =>',
              '    #[' + ', '.join(lanes) + ']',
              '  | n + 1, r, ' + ', '.join(lanes) + ' =>',
              '    roundWith (permute n (r + 1)) VCVio.Algorithms.Keccak.roundConstants[r]!',
              '      ' + args, '',
              '/-- Keccak-f[1600], using 25 scalar lanes across all 24 rounds. -/',
              '@[expose] def f1600 (s : Array UInt64) : Array UInt64 :=',
              '  permute 24 0',
              '    ' + ' '.join(f's[{i}]!' for i in range(25)), '',
              'end CompStark.Keccak', ''])
Path('CompStark/Keccak/Scalar.lean').write_text('\n'.join(lines))
